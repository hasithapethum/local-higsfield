"""Workflow 1 - CHARACTER SHEET CREATOR (Qwen-Image-Edit 2511).

One photo / character image in  ->  front, 3/4, side, back full-body views + face close-up on a neutral
GRAY backdrop, each generated by its own edit pass, then stitched into one sheet.  The sheet is what workflow 2
(the H3 swap) takes as its character reference.

Identity accuracy (v2): every view is edited from the ORIGINAL photo (image 1 = ground truth), with the cleaned
front view as image 2 for pose/cleanliness - views are never re-drawn from each other's mistakes.  The face
close-up is edited from a tight crop of the REAL face (SAM3 face box), not from the whole photo.
"""
from graph import Graph

VIEWS = {
    "front": "a full-body front view, standing straight, facing the camera, arms relaxed at the sides, neutral expression",
    "three_quarter": "a full-body three-quarter view: the whole body and head clearly rotated 45 degrees to the subject's left so one shoulder is nearer the camera, standing, neutral expression",
    "side": "a full-body side profile view facing left (90 degrees), standing straight, arms relaxed",
    "back": "a full-body rear view, seen from directly behind, standing straight, arms relaxed at the sides",
    "face": "a sharp head-and-shoulders face close-up portrait, facing the camera, neutral expression, even soft lighting",
}
SIZES = {"face": (1024, 1024)}
BODY_SIZE = (832, 1248)   # multiples of 16, 2:3 portrait

BG = {
    "gray": ("plain seamless solid neutral medium-gray (#808080) studio backdrop", 8421504),
    "white": ("plain seamless pure white studio backdrop", 16777215),
}

TEMPLATE = (
    "Redraw the exact same person from the reference image as {view}. "
    "Keep identical face, facial features, skin tone, hairstyle and hair color, facial hair, body build and proportions, "
    "and exactly the same outfit, shoes and accessories ({outfit}). "
    "{extra}{bg}, soft even lighting, no shadows on the backdrop, "
    "photorealistic, sharp focus, full detail, character reference sheet, no text, no watermark."
)

TEMPLATE_OTHER = (
    "Redraw the exact same {noun} from the reference image as {view}. "
    "Keep the identical {noun}: same shape and proportions, same fur / skin / material, same colors and markings, "
    "same distinctive details and accessories. {extra}"
    "{bg}, soft even lighting, no shadows on the backdrop, "
    "photorealistic, sharp focus, full detail, reference sheet, no text, no watermark."
)
NOUN = {"animal": "animal", "creature": "character", "vehicle": "vehicle", "object": "object"}
VIEWS_OTHER = {
    "front": "a full front view, facing the camera, whole {noun} visible",
    "three_quarter": "a three-quarter view (turned 45 degrees to the left), whole {noun} visible",
    "side": "a pure side profile view facing left (90 degrees), whole {noun} visible",
    "back": "a rear view, seen from directly behind, whole {noun} visible",
    "face": "a sharp close-up of the {noun}'s head / front detail, facing the camera",
}

LIGHTNING = "Qwen-Image-Edit-2511-Lightning-4steps-V1.0-bf16.safetensors"
SAM3 = "sam3.1_multiplex_fp16.safetensors"


def build(image, seed=42, steps=None, cfg=None, lightning=True, low_mem=False,
          outfit="keep what they are wearing in the reference", extra="", views=None,
          megapixels=1.0, prefix="H3Studio/charsheet", subject="person", bg="gray", oi=None):
    views = views or list(VIEWS)
    steps = steps or (4 if lightning else 30)
    cfg = cfg if cfg is not None else (1.0 if lightning else 4.0)
    bg_text = BG.get(bg, BG["gray"])[0]
    g = Graph(oi)
    G1, G2, G3 = "1 · INPUT + MODELS", "2 · VIEWS (one edit pass each)", "3 · SHEET"

    load = g.add("LoadImage", "① character photo", G1, image=image, ncolor=("#323", "#535"))
    ref = g.add("ImageScaleToTotalPixels", "ref -> ~1 MP", G1, image=load[0], upscale_method="lanczos",
                megapixels=megapixels, resolution_steps=16)
    unet = g.add("UNETLoader", "Qwen-Image-Edit 2511", G1, unet_name="qwen_image_edit_2511_bf16.safetensors",
                 weight_dtype="fp8_e4m3fn" if low_mem else "default")
    clip = g.add("CLIPLoader", "Qwen2.5-VL 7B (fp8)", G1, clip_name="qwen_2.5_vl_7b_fp8_scaled.safetensors",
                 type="qwen_image", device="default")
    vae = g.add("VAELoader", "Qwen-Image VAE", G1, vae_name="qwen_image_vae.safetensors")
    model = unet
    if lightning:
        model = g.add("LoraLoaderModelOnly", "Lightning 4-step LoRA", G1, model=unet[0], lora_name=LIGHTNING,
                      strength_model=1.0)
    ms = g.add("ModelSamplingAuraFlow", None, G1, model=model[0], shift=3.1)
    cn = g.add("CFGNorm", None, G1, model=ms[0], strength=1.0)

    # real-face crop (person only) - the identity source for the face close-up
    face_crop = None
    if subject == "person" and "face" in views:
        sam = g.add("CheckpointLoaderSimple", "SAM 3.1 (face finder)", G1, ckpt_name=SAM3)
        ft = g.add("CLIPTextEncode", "detect face", G1, text="face:1", clip=sam[1])
        fd = g.add("SAM3_Detect", "SAM3: face box in YOUR photo", G1, model=sam[0], image=ref[0], threshold=0.3,
                   refine_iterations=1, individual_masks=False, conditioning=ft[0])
        fc = g.add("CropByBBoxes", "real face crop", G1, image=ref[0], bboxes=fd[1], output_width=768,
                   output_height=768, padding=64, keep_aspect="pad")
        face_crop = g.add("ImageFromBatch", "face crop (first)", G1, image=fc[0], batch_index=0, length=1)

    sheets, bodies = {}, []
    anchor = None   # cleaned FRONT view (image 2 for the other views)
    order = ["front"] + [v for v in views if v != "front"]
    for v in order:
        ex = (extra.strip() + " ") if extra.strip() else ""
        if subject == "person":
            prompt = TEMPLATE.format(view=VIEWS[v], outfit=outfit, extra=ex, bg=bg_text)
        else:
            noun = NOUN.get(subject, "subject")
            prompt = TEMPLATE_OTHER.format(view=VIEWS_OTHER[v].format(noun=noun), noun=noun, extra=ex, bg=bg_text)
        if v == "front" or anchor is None:
            imgs = {"image1": ref[0]}
        elif v == "face" and face_crop is not None:
            prompt += (" Image 1 is a close-up crop of the real face - reproduce exactly this face, skin texture, "
                       "beard / facial hair and hairstyle. Image 2 is the full photo for context.")
            imgs = {"image1": face_crop[0], "image2": ref[0]}
        else:
            prompt += (" Image 1 is the original photo of the subject - it is the ground truth for identity, face, "
                       "hair, outfit and proportions. Image 2 is the same subject already cleaned on the backdrop; "
                       "use it only for framing.")
            imgs = {"image1": ref[0], "image2": anchor[0]}
        pos = g.add("TextEncodeQwenImageEditPlus", f"prompt: {v}", G2, clip=clip[0], prompt=prompt, vae=vae[0], **imgs)
        if lightning or cfg <= 1.0:
            neg = g.add("ConditioningZeroOut", None, G2, conditioning=pos[0])
        else:
            neg = g.add("TextEncodeQwenImageEditPlus", f"neg: {v}", G2, clip=clip[0],
                        prompt="blurry, low quality, deformed, extra limbs, different person, different face, "
                               "different outfit, text, watermark, busy background, cropped body, white background",
                        vae=vae[0], **imgs)
        w, h = SIZES.get(v, BODY_SIZE)
        lat = g.add("EmptySD3LatentImage", None, G2, width=w, height=h, batch_size=1)
        ks = g.add("KSampler", f"sample: {v}", G2, model=cn[0], seed=seed, steps=steps, cfg=cfg,
                   sampler_name="euler", scheduler="simple", positive=pos[0], negative=neg[0],
                   latent_image=lat[0], denoise=1.0)
        dec = g.add("VAEDecode", None, G2, samples=ks[0], vae=vae[0])
        g.add("SaveImage", f"save {v}", G2, images=dec[0], filename_prefix=f"{prefix}_{v}")
        sheets[v] = dec
        if v == "front":
            anchor = g.add("ImageScaleToTotalPixels", "anchor ~1MP", G2, image=dec[0], upscale_method="lanczos",
                           megapixels=megapixels, resolution_steps=16)
        if v != "face":
            bodies.append(dec)

    row = bodies[0]
    for b in bodies[1:]:
        row = g.add("ImageStitch", None, G3, image1=row[0], direction="right", match_image_size=True,
                    spacing_width=0, spacing_color="white", image2=b[0])
    final = row
    if "face" in sheets:
        final = g.add("ImageStitch", "sheet = bodies | face", G3, image1=row[0], direction="right",
                      match_image_size=True, spacing_width=0, spacing_color="white", image2=sheets["face"][0])
    g.add("SaveImage", "★ CHARACTER SHEET", G3, images=final[0], filename_prefix=f"{prefix}_SHEET",
          ncolor=("#232", "#353"))
    g.add("PreviewImage", "preview", G3, images=final[0])
    return g


if __name__ == "__main__":
    import json
    g = build("character.png")
    json.dump(g.to_api(), open("../workflows/01_character_sheet_creator.api.json", "w"), indent=1)
    json.dump(g.to_ui(), open("../workflows/01_character_sheet_creator.json", "w"), indent=1)
    print("nodes:", len(g.nodes))
